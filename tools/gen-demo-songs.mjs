// Embeds the demo MIDI files (midi/*.mid) into the web app as web/demo-songs.js:
//   node tools/gen-demo-songs.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const MUTOPIA = 'https://www.mutopiaproject.org/ftp/';

// `path` is the location of the file below the Mutopia Project's ftp/ directory.
// `volume` is the output level the song is played at (amplitude, 1 = the
// level of the volume slider), set by ear to even out the five pieces.
const SONGS = [
  {
    title: 'Clair de lune',
    composer: 'Claude Debussy',
    path: 'DebussyC/L75/debussy_Ste_Bergamesq_Clair/debussy_Ste_Bergamesq_Clair.mid',
    volume: 0.96,
  },
  {
    title: 'Étude Op. 10, No. 1',
    composer: 'Frédéric Chopin',
    path: 'ChopinFF/O10/chp-10-01/chp-10-01.mid',
    volume: 0.501,
  },
  {
    title: 'Piano Sonata No. 8 in C Minor, Op. 13 "Pathétique" – I. Grave – Allegro di molto e con brio',
    composer: 'Ludwig van Beethoven',
    path: 'BeethovenLv/O13/pathetique-1/pathetique-1.mid',
    volume: 0.576,
  },
  {
    title: 'Rondo alla Turca (Piano Sonata No. 11 in A Major, K. 331 – III)',
    composer: 'Wolfgang Amadeus Mozart',
    path: 'MozartWA/KV331/KV331_3_RondoAllaTurca/KV331_3_RondoAllaTurca.mid',
    volume: 1.039,
  },
  {
    title: 'Für Elise (Bagatelle No. 25 in A Minor, WoO 59)',
    composer: 'Ludwig van Beethoven',
    path: 'BeethovenLv/WoO59/fur_Elise_WoO59/fur_Elise_WoO59.mid',
    volume: 1.757,
  },
];

const entries = [];
for (const s of SONGS) {
  const file = s.path.split('/').pop();
  const data = (await readFile(join(root, 'midi', file))).toString('base64');
  entries.push(`  {
    title: ${JSON.stringify(s.title)},
    composer: ${JSON.stringify(s.composer)},
    file: ${JSON.stringify(file)},
    url: ${JSON.stringify(MUTOPIA + s.path)},
    volume: ${s.volume},
    data: ${JSON.stringify(data)},
  },`);
}

const out = `// Generated by tools/gen-demo-songs.mjs from midi/*.mid. Do not edit.
// Public domain MIDI data distributed by the Mutopia Project
// (https://www.mutopiaproject.org/). \`data\` is the .mid file in base64,
// \`volume\` the output level the song is played at (1 = the volume slider).
export const DEMO_SONGS = [
${entries.join('\n')}
];
`;
await writeFile(join(root, 'web', 'demo-songs.js'), out);
console.log(`web/demo-songs.js: ${SONGS.length} songs, ${out.length} bytes`);
